from __future__ import annotations

import argparse
import json
import math
import random
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Tuple

from PIL import Image


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_DATA = Path("data_v2/dataset.yaml")
DEFAULT_OUTPUT_ROOT = Path("data_big_v1")

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"}
DEFAULT_VARIANTS = ("scene_grouped", "mixed_stress", "sparse")
RESAMPLE_BILINEAR = getattr(getattr(Image, "Resampling", Image), "BILINEAR")


@dataclass(frozen=True)
class Label:
    cls: int
    cx: float
    cy: float
    w: float
    h: float


@dataclass(frozen=True)
class Sample:
    image: Path
    label: Path
    width: int
    height: int
    scene_key: str
    labels: Tuple[Label, ...]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build pseudo 10000x10000 big-image YOLO datasets from data_v2 crops."
    )
    parser.add_argument("--source-data", default=str(DEFAULT_SOURCE_DATA))
    parser.add_argument("--source-split", default="val")
    parser.add_argument("--output-root", default=str(DEFAULT_OUTPUT_ROOT))
    parser.add_argument("--output-split", default="val")
    parser.add_argument("--big-width", type=int, default=10000)
    parser.add_argument("--big-height", type=int, default=10000)
    parser.add_argument("--cell-size", type=int, default=800)
    parser.add_argument(
        "--variants",
        default=",".join(DEFAULT_VARIANTS),
        help="Comma-separated variants: scene_grouped,mixed_stress,sparse.",
    )
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--jpeg-quality", type=int, default=95)
    parser.add_argument("--background", default="114,114,114")
    parser.add_argument(
        "--limit-source-images",
        type=int,
        default=0,
        help="Use only the first N source images after loading. 0 means all.",
    )
    parser.add_argument(
        "--max-big-per-variant",
        type=int,
        default=0,
        help="Maximum generated big images for non-sparse variants. 0 means all.",
    )
    parser.add_argument("--num-sparse-images", type=int, default=3)
    parser.add_argument("--sparse-patches-per-image", type=int, default=12)
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite files with the same generated names. Existing extra files are not deleted.",
    )
    parser.add_argument("--dry-run", action="store_true", help="Print the plan without writing files.")
    return parser.parse_args()


def resolve_project_path(value: str) -> Path:
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = PROJECT_ROOT / path
    return path.resolve()


def load_yaml(path: Path) -> Dict:
    try:
        import yaml
    except ImportError as exc:
        raise RuntimeError("PyYAML is required to read dataset YAML files.") from exc

    with path.open("r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    if not isinstance(data, dict):
        raise ValueError(f"Dataset YAML is not a mapping: {path}")
    return data


def dump_dataset_yaml(source_cfg: Dict, output_root: Path, output_split: str, split_names: Sequence[str]) -> str:
    lines = [
        "# Generated by scripts/build_big_mosaic_dataset.py",
        f"path: {str(output_root).replace(chr(92), '/')}",
    ]
    primary_split = split_names[0]
    lines.append(f"{output_split}: images/{primary_split}")
    for split_name in split_names:
        lines.append(f"{split_name}: images/{split_name}")

    nc = int(source_cfg.get("nc", len(source_cfg.get("names", []))))
    lines.extend(["", f"nc: {nc}", "", "names:"])
    names = source_cfg.get("names", {})
    if isinstance(names, dict):
        items = sorted((int(k), v) for k, v in names.items())
    else:
        items = list(enumerate(names))
    for idx, name in items:
        lines.append(f"  {idx}: {name}")
    return "\n".join(lines) + "\n"


def resolve_data_root(data_yaml: Path, cfg: Dict) -> Path:
    root_value = cfg.get("path", data_yaml.parent)
    root = Path(str(root_value)).expanduser()
    if not root.is_absolute():
        root = data_yaml.parent / root
    return root.resolve()


def read_image_list(list_path: Path, data_root: Path) -> List[Path]:
    image_paths: List[Path] = []
    with list_path.open("r", encoding="utf-8") as f:
        for line in f:
            raw = line.strip()
            if not raw:
                continue
            path = Path(raw).expanduser()
            if not path.is_absolute():
                path = data_root / path
            image_paths.append(path.resolve())
    return image_paths


def resolve_split_sources(data_yaml: Path, cfg: Dict, split: str) -> List[Path]:
    if split not in cfg:
        raise KeyError(f"Split '{split}' was not found in {data_yaml}")

    data_root = resolve_data_root(data_yaml, cfg)
    split_value = cfg[split]
    raw_sources: Sequence[str]
    if isinstance(split_value, (list, tuple)):
        raw_sources = [str(item) for item in split_value]
    else:
        raw_sources = [str(split_value)]

    image_paths: List[Path] = []
    for raw_source in raw_sources:
        source = Path(raw_source).expanduser()
        if not source.is_absolute():
            source = data_root / source
        source = source.resolve()
        if source.is_dir():
            image_paths.extend(
                sorted(p for p in source.rglob("*") if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES)
            )
        elif source.is_file() and source.suffix.lower() == ".txt":
            image_paths.extend(read_image_list(source, data_root))
        elif source.is_file() and source.suffix.lower() in IMAGE_SUFFIXES:
            image_paths.append(source)
        else:
            raise FileNotFoundError(f"Split source does not exist or has no supported images: {source}")

    unique_paths = sorted(dict.fromkeys(image_paths))
    if not unique_paths:
        raise FileNotFoundError(f"No images found for split '{split}' in {data_yaml}")
    return unique_paths


def label_path_for_image(image_path: Path, data_root: Path, split: str) -> Path:
    parts = list(image_path.parts)
    for idx in range(len(parts) - 1, -1, -1):
        if parts[idx] == "images":
            parts[idx] = "labels"
            return Path(*parts).with_suffix(".txt")
    return (data_root / "labels" / split / image_path.with_suffix(".txt").name).resolve()


def read_labels(path: Path) -> Tuple[Label, ...]:
    labels: List[Label] = []
    if not path.exists():
        return tuple(labels)
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            raw = line.strip()
            if not raw:
                continue
            parts = raw.split()
            if len(parts) < 5:
                raise ValueError(f"Invalid YOLO label at {path}:{line_no}: {raw}")
            labels.append(
                Label(
                    cls=int(float(parts[0])),
                    cx=float(parts[1]),
                    cy=float(parts[2]),
                    w=float(parts[3]),
                    h=float(parts[4]),
                )
            )
    return tuple(labels)


def scene_key_from_stem(stem: str) -> str:
    stem = re.sub(r"_crop\d+$", "", stem)
    stem = re.sub(r"_crop\d+_", "_", stem)
    return stem


def load_samples(data_yaml: Path, cfg: Dict, split: str, limit: int) -> List[Sample]:
    data_root = resolve_data_root(data_yaml, cfg)
    image_paths = resolve_split_sources(data_yaml, cfg, split)
    if limit > 0:
        image_paths = image_paths[:limit]

    samples: List[Sample] = []
    for image_path in image_paths:
        with Image.open(image_path) as image:
            width, height = image.size
        label_path = label_path_for_image(image_path, data_root, split)
        samples.append(
            Sample(
                image=image_path,
                label=label_path,
                width=width,
                height=height,
                scene_key=scene_key_from_stem(image_path.stem),
                labels=read_labels(label_path),
            )
        )
    return samples


def parse_variants(raw: str) -> List[str]:
    variants = [item.strip() for item in raw.split(",") if item.strip()]
    unknown = sorted(set(variants) - set(DEFAULT_VARIANTS))
    if unknown:
        raise ValueError(f"Unknown variants: {unknown}")
    if not variants:
        raise ValueError("--variants cannot be empty.")
    return variants


def parse_color(raw: str) -> Tuple[int, int, int]:
    parts = [int(part.strip()) for part in raw.split(",")]
    if len(parts) != 3 or any(part < 0 or part > 255 for part in parts):
        raise ValueError("--background must be R,G,B with values in [0,255].")
    return parts[0], parts[1], parts[2]


def grid_positions(big_width: int, big_height: int, cell_size: int) -> List[Tuple[int, int]]:
    if cell_size <= 0:
        raise ValueError("--cell-size must be positive.")
    cols = big_width // cell_size
    rows = big_height // cell_size
    if cols <= 0 or rows <= 0:
        raise ValueError("--cell-size is larger than the requested big image.")
    return [(col * cell_size, row * cell_size) for row in range(rows) for col in range(cols)]


def chunked(items: Sequence[Sample], size: int) -> Iterable[List[Sample]]:
    for start in range(0, len(items), size):
        yield list(items[start : start + size])


def samples_for_variant(samples: Sequence[Sample], variant: str, rng: random.Random) -> List[Sample]:
    ordered = list(samples)
    if variant == "scene_grouped":
        ordered.sort(key=lambda sample: (sample.scene_key, sample.image.name))
    elif variant == "mixed_stress":
        rng.shuffle(ordered)
        ordered.sort(key=lambda sample: len(sample.labels), reverse=True)
    else:
        raise ValueError(f"samples_for_variant does not handle sparse variant: {variant}")
    return ordered


def transform_label(label: Label, sample: Sample, offset_x: int, offset_y: int, scale: float, big_width: int, big_height: int) -> str:
    abs_cx = label.cx * sample.width * scale + offset_x
    abs_cy = label.cy * sample.height * scale + offset_y
    abs_w = label.w * sample.width * scale
    abs_h = label.h * sample.height * scale
    return (
        f"{label.cls} "
        f"{abs_cx / big_width:.6f} {abs_cy / big_height:.6f} "
        f"{abs_w / big_width:.6f} {abs_h / big_height:.6f}"
    )


def paste_sample(
    canvas: Image.Image,
    sample: Sample,
    offset_x: int,
    offset_y: int,
    cell_size: int,
    big_width: int,
    big_height: int,
) -> Tuple[List[str], Dict]:
    with Image.open(sample.image) as source_image:
        source_image = source_image.convert("RGB")
        scale = min(cell_size / sample.width, cell_size / sample.height, 1.0)
        paste_width = int(round(sample.width * scale))
        paste_height = int(round(sample.height * scale))
        if scale != 1.0:
            source_image = source_image.resize((paste_width, paste_height), RESAMPLE_BILINEAR)
        canvas.paste(source_image, (offset_x, offset_y))

    label_lines = [
        transform_label(label, sample, offset_x, offset_y, scale, big_width, big_height)
        for label in sample.labels
    ]
    placement = {
        "source_image": str(sample.image),
        "source_label": str(sample.label),
        "scene_key": sample.scene_key,
        "offset": [offset_x, offset_y],
        "pasted_size": [paste_width, paste_height],
        "scale": scale,
        "targets": len(sample.labels),
    }
    return label_lines, placement


def assert_outputs_available(paths: Sequence[Path], overwrite: bool) -> None:
    if overwrite:
        return
    existing = [path for path in paths if path.exists()]
    if existing:
        preview = "\n".join(str(path) for path in existing[:5])
        raise FileExistsError(
            "Generated output files already exist. Use --overwrite to replace same-name files.\n"
            f"First existing files:\n{preview}"
        )


def write_big_image(
    samples: Sequence[Sample],
    positions: Sequence[Tuple[int, int]],
    variant: str,
    split_name: str,
    image_index: int,
    output_root: Path,
    args: argparse.Namespace,
    background: Tuple[int, int, int],
) -> Dict:
    image_dir = output_root / "images" / split_name
    label_dir = output_root / "labels" / split_name
    image_path = image_dir / f"big_{split_name}_{image_index:06d}.jpg"
    label_path = label_dir / f"big_{split_name}_{image_index:06d}.txt"
    assert_outputs_available([image_path, label_path], args.overwrite)

    canvas = Image.new("RGB", (args.big_width, args.big_height), background)
    label_lines: List[str] = []
    placements: List[Dict] = []
    for sample, (offset_x, offset_y) in zip(samples, positions):
        sample_labels, placement = paste_sample(
            canvas=canvas,
            sample=sample,
            offset_x=offset_x,
            offset_y=offset_y,
            cell_size=args.cell_size,
            big_width=args.big_width,
            big_height=args.big_height,
        )
        label_lines.extend(sample_labels)
        placements.append(placement)

    image_dir.mkdir(parents=True, exist_ok=True)
    label_dir.mkdir(parents=True, exist_ok=True)
    canvas.save(image_path, quality=args.jpeg_quality)
    label_path.write_text("\n".join(label_lines) + ("\n" if label_lines else ""), encoding="utf-8")

    return {
        "variant": variant,
        "split": split_name,
        "big_image": str(image_path),
        "big_label": str(label_path),
        "big_size": [args.big_width, args.big_height],
        "source_images": len(samples),
        "targets": len(label_lines),
        "placements": placements,
    }


def write_manifest(records: Sequence[Dict], path: Path, overwrite: bool) -> None:
    assert_outputs_available([path], overwrite)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for record in records:
            json.dump(record, f, ensure_ascii=False)
            f.write("\n")


def plan_counts(samples: Sequence[Sample], variants: Sequence[str], capacity: int, args: argparse.Namespace) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    for variant in variants:
        if variant == "sparse":
            counts[variant] = args.num_sparse_images
        else:
            needed = math.ceil(len(samples) / capacity)
            if args.max_big_per_variant > 0:
                needed = min(needed, args.max_big_per_variant)
            counts[variant] = needed
    return counts


def build_sparse_batches(samples: Sequence[Sample], positions: Sequence[Tuple[int, int]], rng: random.Random, args: argparse.Namespace) -> List[Tuple[List[Sample], List[Tuple[int, int]]]]:
    positive_samples = [sample for sample in samples if sample.labels]
    sample_pool = positive_samples or list(samples)
    batches: List[Tuple[List[Sample], List[Tuple[int, int]]]] = []
    patch_count = min(args.sparse_patches_per_image, len(positions))
    for _ in range(args.num_sparse_images):
        chosen_samples = [rng.choice(sample_pool) for _ in range(patch_count)]
        chosen_positions = rng.sample(list(positions), patch_count)
        batches.append((chosen_samples, chosen_positions))
    return batches


def build_variant(
    samples: Sequence[Sample],
    variant: str,
    split_name: str,
    output_root: Path,
    positions: Sequence[Tuple[int, int]],
    rng: random.Random,
    args: argparse.Namespace,
    background: Tuple[int, int, int],
) -> List[Dict]:
    records: List[Dict] = []
    if variant == "sparse":
        batches = build_sparse_batches(samples, positions, rng, args)
    else:
        ordered = samples_for_variant(samples, variant, rng)
        chunks = list(chunked(ordered, len(positions)))
        if args.max_big_per_variant > 0:
            chunks = chunks[: args.max_big_per_variant]
        batches = [(chunk, list(positions[: len(chunk)])) for chunk in chunks]

    for image_index, (batch_samples, batch_positions) in enumerate(batches, start=1):
        records.append(
            write_big_image(
                samples=batch_samples,
                positions=batch_positions,
                variant=variant,
                split_name=split_name,
                image_index=image_index,
                output_root=output_root,
                args=args,
                background=background,
            )
        )
        print(
            f"generated split={split_name} image={image_index}/{len(batches)} "
            f"sources={len(batch_samples)} targets={records[-1]['targets']}",
            flush=True,
        )
    return records


def main() -> int:
    args = parse_args()
    source_data = resolve_project_path(args.source_data)
    output_root = resolve_project_path(args.output_root)
    variants = parse_variants(args.variants)
    background = parse_color(args.background)
    cfg = load_yaml(source_data)
    samples = load_samples(source_data, cfg, args.source_split, args.limit_source_images)
    positions = grid_positions(args.big_width, args.big_height, args.cell_size)
    capacity = len(positions)
    counts = plan_counts(samples, variants, capacity, args)

    print(f"source_data={source_data}", flush=True)
    print(f"source_split={args.source_split} source_images={len(samples)}", flush=True)
    print(
        f"big_size={args.big_width}x{args.big_height} cell_size={args.cell_size} "
        f"grid_capacity={capacity}",
        flush=True,
    )
    print(f"variants={counts}", flush=True)
    if args.dry_run:
        print("dry_run=ok", flush=True)
        return 0

    rng = random.Random(args.seed)
    all_split_names: List[str] = []
    all_records: Dict[str, List[Dict]] = {}
    for variant in variants:
        split_name = f"{args.output_split}_{variant}"
        all_split_names.append(split_name)
        records = build_variant(
            samples=samples,
            variant=variant,
            split_name=split_name,
            output_root=output_root,
            positions=positions,
            rng=rng,
            args=args,
            background=background,
        )
        all_records[split_name] = records
        manifest_path = output_root / "manifests" / f"{split_name}_manifest.jsonl"
        write_manifest(records, manifest_path, args.overwrite)
        print(f"manifest={manifest_path}", flush=True)

    dataset_yaml = output_root / "dataset.yaml"
    assert_outputs_available([dataset_yaml], args.overwrite)
    dataset_yaml.write_text(dump_dataset_yaml(cfg, output_root, args.output_split, all_split_names), encoding="utf-8")

    summary = {
        "source_data": str(source_data),
        "source_split": args.source_split,
        "source_images": len(samples),
        "output_root": str(output_root),
        "output_split_alias": args.output_split,
        "big_size": [args.big_width, args.big_height],
        "cell_size": args.cell_size,
        "grid_capacity": capacity,
        "variants": {
            split_name: {
                "images": len(records),
                "targets": sum(record["targets"] for record in records),
                "manifest": str(output_root / "manifests" / f"{split_name}_manifest.jsonl"),
            }
            for split_name, records in all_records.items()
        },
        "dataset_yaml": str(dataset_yaml),
    }
    summary_path = output_root / "mosaic_summary.json"
    assert_outputs_available([summary_path], args.overwrite)
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"dataset_yaml={dataset_yaml}", flush=True)
    print(f"summary={summary_path}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
