"""Build reproducible training manifests for report baseline and data ablations."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = ROOT / "data_v2"
DEFAULT_ASSIGNMENTS = DATA_ROOT / "report_split_v16" / "assignments.csv"
DEFAULT_DATASET = DATA_ROOT / "report_split_v16" / "dataset_report.yaml"
DEFAULT_OUTPUT = DATA_ROOT / "report_ablation_v16"
VARIANT_KINDS = {
    "official": {"official"},
    "official_external": {"official", "external_train_only"},
    "full": {"official", "external_train_only", "derived"},
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assignments", type=Path, default=DEFAULT_ASSIGNMENTS)
    parser.add_argument("--source-dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--variant", choices=[*VARIANT_KINDS, "all"], default="official")
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def relocate(server_path: str) -> Path:
    normalized = server_path.replace("\\", "/")
    marker = "/data_v2/"
    if marker not in normalized:
        raise ValueError(f"Cannot relocate dataset path: {server_path}")
    return DATA_ROOT / normalized.split(marker, 1)[1]


def load_names(path: Path) -> list[str]:
    names: dict[int, str] = {}
    in_names = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() == "names:":
            in_names = True
            continue
        if in_names:
            stripped = line.strip()
            if not stripped:
                continue
            if not line.startswith(" "):
                break
            key, value = stripped.split(":", 1)
            names[int(key)] = value.strip().strip("'\"")
    if not names:
        raise ValueError(f"No class names found in {path}")
    return [names[index] for index in range(len(names))]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def write_manifest(path: Path, images: list[Path], overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"output already exists: {path}; pass --overwrite to refresh it")
    path.write_text("\n".join(image.as_posix() for image in images) + "\n", encoding="utf-8")


def yaml_text(output_dir: Path, variant: str, names: list[str]) -> str:
    lines = [
        "# Generated by scripts/prepare_report_ablation_datasets.py",
        f"path: {output_dir.as_posix()}",
        f"train: train_{variant}.txt",
        "val: calibration.txt",
        "test: validation.txt",
        "calibration: calibration.txt",
        "validation: validation.txt",
        "",
        f"nc: {len(names)}",
        "",
        "names:",
    ]
    lines.extend(f"  {index}: {name}" for index, name in enumerate(names))
    return "\n".join(lines) + "\n"


def main() -> int:
    args = parse_args()
    assignments_path = args.assignments.resolve()
    source_dataset = args.source_dataset.resolve()
    output_dir = args.output_dir.resolve()
    for path in (assignments_path, source_dataset):
        if not path.is_file():
            raise FileNotFoundError(path)
    output_dir.mkdir(parents=True, exist_ok=True)
    names = load_names(source_dataset)
    with assignments_path.open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))

    calibration = sorted(relocate(row["image"]) for row in rows if row["assigned_split"] == "calibration")
    validation = sorted(relocate(row["image"]) for row in rows if row["assigned_split"] == "validation")
    missing_eval = [path for path in calibration + validation if not path.is_file()]
    if missing_eval:
        raise FileNotFoundError(f"missing calibration/validation image: {missing_eval[0]}")

    calibration_path = output_dir / "calibration.txt"
    validation_path = output_dir / "validation.txt"
    write_manifest(calibration_path, calibration, args.overwrite)
    write_manifest(validation_path, validation, args.overwrite)

    variants = list(VARIANT_KINDS) if args.variant == "all" else [args.variant]
    result = {
        "source_assignments": assignments_path.as_posix(),
        "calibration_images": len(calibration),
        "validation_images": len(validation),
        "variants": {},
    }
    for variant in variants:
        kinds = VARIANT_KINDS[variant]
        train = sorted(
            relocate(row["image"])
            for row in rows
            if row["assigned_split"] == "train" and row["sample_kind"] in kinds
        )
        missing = [path for path in train if not path.is_file()]
        if missing:
            raise FileNotFoundError(
                f"variant {variant} is missing {len(missing)} image(s); first missing path: {missing[0]}"
            )
        manifest_path = output_dir / f"train_{variant}.txt"
        dataset_path = output_dir / f"dataset_{variant}.yaml"
        write_manifest(manifest_path, train, args.overwrite)
        if dataset_path.exists() and not args.overwrite:
            raise FileExistsError(f"output already exists: {dataset_path}; pass --overwrite to refresh it")
        dataset_path.write_text(yaml_text(output_dir, variant, names), encoding="utf-8")
        kind_counts = {
            kind: sum(
                1
                for row in rows
                if row["assigned_split"] == "train" and row["sample_kind"] == kind and kind in kinds
            )
            for kind in sorted(kinds)
        }
        result["variants"][variant] = {
            "training_images": len(train),
            "sample_kind_counts": kind_counts,
            "manifest": manifest_path.as_posix(),
            "manifest_sha256": sha256(manifest_path),
            "dataset_yaml": dataset_path.as_posix(),
        }

    summary_path = output_dir / f"summary_{args.variant}.json"
    if summary_path.exists() and not args.overwrite:
        raise FileExistsError(f"output already exists: {summary_path}; pass --overwrite to refresh it")
    summary_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False, indent=2))
    print("REPORT_ABLATION_DATASETS=PASSED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
